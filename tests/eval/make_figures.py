r"""Generate TikZ/pgfplots figures for the scaling evaluation of the paper.

Reads the parsed results (results.csv, produced by parse_eval_results.py) and
emits ready-to-include LaTeX figures answering the two research questions:

- RQ1: scalability with the CFM depth
  (x-axis = depth, one line per cardinality interval upper bound)
- RQ2: scalability with the cardinality interval sizes
  (x-axis = interval upper bound, one line per depth)

Outputs (default into tests/eval/figures/):
  - rq1_depth.tex, rq2_interval.tex
      Complete figure environments (pgfplots groupplots): one column per
      interaction size t, top row = sampling time (log scale), bottom row =
      sample size.
  - standalone/axis_*.tex
      Single-axis files (one per RQ/metric/t) for custom layouts; \input them
      inside a tikzpicture.

Usage:
    python3 make_figures.py [--results tests/eval/results/results.csv]
                            [--out tests/eval/figures]
"""

import argparse
import csv
from pathlib import Path

TS = [1, 2, 3]

# Okabe-Ito colorblind-safe palette (RGB triplets) and matching pgfplots marks
COLORS = [
    "0,114,178",
    "213,94,0",
    "0,158,115",
    "230,159,0",
    "204,121,167",
    "86,180,233",
]
MARKS = ["*", "square*", "triangle*", "diamond*", "pentagon*", "star"]

PREAMBLE = (
    "% Auto-generated by make_figures.py -- do not edit manually.\n"
    "% Required LaTeX setup (in the main document):\n"
    "%   \\usepackage{pgfplots}\n"
    "%   \\pgfplotsset{compat=1.18}\n"
    "%   \\usepgfplotslibrary{groupplots}  % only for the group figures\n"
)

METRICS = [
    ("Sampling time [s]", "avg_time_seconds", True),
    ("Average sample size", "avg_sample_size", False),
]


def load_results(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as fh:
        rows = [row for row in csv.DictReader(fh) if row["status"] == "ok"]
    if not rows:
        raise SystemExit(f"No usable rows (status=ok) in {path}")
    return rows


def build_series(
    rows: list[dict[str, str]], x_key: str, line_key: str, metric: str
) -> list[tuple[float, list[tuple[float, float]]]]:
    """Return a sorted list of (line_value, [(x, y), ...]) series."""
    line_values = sorted({float(row[line_key]) for row in rows})
    series = []
    for value in line_values:
        points = sorted(
            (float(row[x_key]), float(row[metric]))
            for row in rows
            if float(row[line_key]) == value
        )
        series.append((value, points))
    return series


def fmt(value: float) -> str:
    return f"{value:.8g}"


def legend_label(line_key: str, value: float) -> str:
    symbol = "u" if line_key == "interval" else "d"
    return f"$\\mathrm{{{symbol}}}{{=}}{int(value)}$"


def plot_commands(
    series: list[tuple[float, list[tuple[float, float]]]],
    labels: list[str],
    show_legend: bool,
) -> str:
    lines = []
    for i, (_value, points) in enumerate(series):
        coords = " ".join(f"({fmt(x)},{fmt(y)})" for x, y in points)
        lines.append(
            f"\\addplot+[color=cf{i}, mark={MARKS[i]}, mark size=1.5pt, "
            f"line width=0.9pt, mark options={{solid}}] coordinates {{ {coords} }};"
        )
        if show_legend:
            lines.append(f"\\addlegendentry{{{labels[i]}}}")
    return "\n".join(lines)


def axis_options(
    *,
    title: str,
    xlabel: str,
    ylabel: str,
    log_y: bool,
    xticks: str,
    width: str,
    height: str,
    show_legend: bool,
) -> str:
    opts = [
        f"width={width}",
        f"height={height}",
        f"title={{{title}}}",
        f"xlabel={{{xlabel}}}",
        f"ylabel={{{ylabel}}}",
        f"xtick={{{xticks}}}",
        "grid=major",
        "tick label style={font=\\small}",
        "label style={font=\\small}",
        "title style={font=\\small}",
        "scaled y ticks=false",
    ]
    if log_y:
        opts += ["ymode=log", "log basis y=10", "log origin=infty"]
    else:
        opts += ["yticklabel style={/pgf/number format/fixed}"]
    if show_legend:
        opts += [
            "legend pos=north west",
            "legend style={font=\\scriptsize, draw=none, fill=white, "
            "fill opacity=0.85, text opacity=1}",
            "legend cell align=left",
        ]
    return ",\n".join(opts)


def color_definitions() -> str:
    return "\n".join(
        f"\\definecolor{{cf{i}}}{{RGB}}{{{color}}}" for i, color in enumerate(COLORS)
    )


def render_standalone(
    series: list[tuple[float, list[tuple[float, float]]]],
    labels: list[str],
    xlabel: str,
    ylabel: str,
    log_y: bool,
    xticks: str,
    title: str,
) -> str:
    options = axis_options(
        title=title,
        xlabel=xlabel,
        ylabel=ylabel,
        log_y=log_y,
        xticks=xticks,
        width="0.45\\textwidth",
        height="0.32\\textwidth",
        show_legend=True,
    )
    body = "\n".join(
        [
            "\\begin{axis}[",
            options,
            "]",
            plot_commands(series, labels, show_legend=True),
            "\\end{axis}",
        ]
    )
    return f"{PREAMBLE}\n{color_definitions()}\n\n{body}\n"


def render_group_figure(
    caption: str,
    label: str,
    xlabel: str,
    xticks: str,
    per_t: dict[int, dict[str, list[tuple[float, list[tuple[float, float]]]]]],
    labels: list[str],
) -> str:
    cells = []
    for row, (ylabel, _metric, log_y) in enumerate(METRICS):
        for col, t in enumerate(TS):
            show_legend = row == 0 and col == 0
            options = axis_options(
                title=f"$t={t}$" if row == 0 else "",
                xlabel=xlabel if row == len(METRICS) - 1 else "",
                ylabel=ylabel,
                log_y=log_y,
                xticks=xticks,
                width="0.34\\textwidth",
                height="0.28\\textwidth",
                show_legend=show_legend,
            )
            cells.append(
                "\n".join(
                    [
                        f"\\nextgroupplot[{options}]",
                        plot_commands(per_t[t][ylabel], labels, show_legend),
                    ]
                )
            )
    groupplot = "\n\n".join(cells)
    return "\n".join(
        [
            PREAMBLE,
            color_definitions(),
            "\\begin{figure}[tb]",
            "\\centering",
            "\\begin{tikzpicture}",
            "\\begin{groupplot}[",
            "    group style={",
            "        group size=3 by 2,",
            "        horizontal sep=1.5cm,",
            "        vertical sep=1.5cm,",
            "        xlabels at=edge bottom,",
            "        ylabels at=edge left,",
            "    },",
            "]",
            groupplot,
            "\\end{groupplot}",
            "\\end{tikzpicture}",
            f"\\caption{{{caption}}}",
            f"\\label{{{label}}}",
            "\\end{figure}",
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results", type=Path, default=Path("tests/eval/results/results.csv")
    )
    parser.add_argument("--out", type=Path, default=Path("tests/eval/figures"))
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    standalone_dir = args.out / "standalone"
    standalone_dir.mkdir(parents=True, exist_ok=True)

    rows = load_results(args.results)

    configs = [
        (1, "depth", "interval", "CFM depth", "rq1_depth"),
        (2, "interval", "depth", "Interval upper bound", "rq2_interval"),
    ]
    for rq, x_key, line_key, xlabel, name in configs:
        xticks = ",".join(
            str(int(v)) for v in sorted({float(row[x_key]) for row in rows})
        )
        labels = [
            legend_label(line_key, value)
            for value, _ in build_series(rows, x_key, line_key, "avg_time_seconds")
        ]

        per_t: dict[int, dict[str, list[tuple[float, list[tuple[float, float]]]]]] = {}
        for t in TS:
            rows_t = [row for row in rows if int(float(row["t"])) == t]
            per_t[t] = {
                ylabel: build_series(rows_t, x_key, line_key, metric)
                for ylabel, metric, _log_y in METRICS
            }

        # Standalone single-axis files: one per metric and t
        for ylabel, metric, log_y in METRICS:
            for t in TS:
                rows_t = [row for row in rows if int(float(row["t"])) == t]
                series = build_series(rows_t, x_key, line_key, metric)
                short = "time" if log_y else "size"
                text = render_standalone(
                    series, labels, xlabel, ylabel, log_y, xticks, title=f"$t={t}$"
                )
                path = standalone_dir / f"axis_rq{rq}_{short}_t{t}.tex"
                path.write_text(text)
                print(f"Wrote {path}")

        if rq == 1:
            caption = (
                "Scalability of the instance-set $t$-wise sampling algorithm with "
                "the CFM depth. Top: average sampling time (logarithmic scale); "
                "bottom: average sample size. Columns show interaction sizes "
                "$t\\in\\{1,2,3\\}$; lines show cardinality interval upper bounds "
                "$u$. Averages over $r=5$ repetitions with $m=5$ resampling rounds."
            )
        else:
            caption = (
                "Scalability of the instance-set $t$-wise sampling algorithm with "
                "the cardinality interval upper bound $u$. Top: average sampling "
                "time (logarithmic scale); bottom: average sample size. Columns "
                "show interaction sizes $t\\in\\{1,2,3\\}$; lines show CFMs of "
                "different depths $d$. Averages over $r=5$ repetitions with "
                "$m=5$ resampling rounds."
            )
        figure = render_group_figure(
            caption, f"fig:rq{rq}", xlabel, xticks, per_t, labels
        )
        figure_path = args.out / f"{name}.tex"
        figure_path.write_text(figure)
        print(f"Wrote {figure_path}")


if __name__ == "__main__":
    main()
