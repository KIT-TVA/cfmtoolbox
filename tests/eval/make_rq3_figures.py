r"""Generate TikZ/pgfplots figures for the parameter-influence evaluation (RQ3).

Reads the parsed parameter results (results.csv, produced by
parse_parameter_eval_results.py) and emits ready-to-include LaTeX figures with

- x-axis: the value of the varied parameter,
- y-axis: average sampling time (log scale) or average sample size,
- one line per model (Model A-E and multiplayer-game).

The experiments and their fixed settings are:
  - t experiment: t in {1,2,3},    m = 5, c = 50  -> sampling time
  - m experiment: m in {1,5,10,15,20}, t = 2, c = 50 -> time + sample size
  - c experiment: c in {50,500,1000}, t = 2, m = 5  -> sampling time

Outputs (default into tests/eval/figures/):
  - rq3_time.tex
      Figure with one axis per experiment (t, m, c), y = sampling time (log).
  - rq3_size.tex
      Figure with a single axis for the m experiment, y = average sample size.
  - standalone/axis_rq3_time_{t,m,c}.tex, standalone/axis_rq3_size_m.tex
      Single-axis files for custom layouts; \input them inside a tikzpicture.

Usage:
    python3 make_rq3_figures.py [--results tests/eval/param_results/results.csv]
                                [--out tests/eval/figures]
"""

import argparse
import csv
from pathlib import Path

# Display order of the models (stems from results.csv)
MODEL_ORDER = [
    "model_a",
    "model_b",
    "model_c",
    "model_d",
    "model_e",
    "multiplayer_game",
]


def display_name(stem: str) -> str:
    if stem.startswith("model_"):
        return f"Model {stem.removeprefix('model_').upper()}"
    return stem.replace("_", "-")


# Experiment -> (x label, [(metric column, y label, log y, file tag), ...])
EXPERIMENTS = {
    "t": (
        "Interaction size $t$",
        [("avg_time_seconds", "Sampling time [s]", True, "time")],
    ),
    "m": (
        "Resampling rounds $m$",
        [
            ("avg_time_seconds", "Sampling time [s]", True, "time"),
            ("avg_sample_size", "Average sample size", False, "size"),
        ],
    ),
    "c": ("Cache size $c$", [("avg_time_seconds", "Sampling time [s]", True, "time")]),
}

# Okabe-Ito colorblind-safe palette (RGB triplets) and matching pgfplots marks
COLORS = [
    "0,114,178",
    "213,94,0",
    "0,158,115",
    "230,159,0",
    "204,121,167",
    "86,180,233",
]
MARKS = ["*", "square*", "triangle*", "diamond*", "pentagon*", "star"]

PREAMBLE = (
    "% Auto-generated by make_rq3_figures.py -- do not edit manually.\n"
    "% Required LaTeX setup (in the main document):\n"
    "%   \\usepackage{pgfplots}\n"
    "%   \\pgfplotsset{compat=1.18}\n"
    "%   \\usepgfplotslibrary{groupplots}  % only for the group figure\n"
)


def load_results(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as fh:
        rows = [row for row in csv.DictReader(fh) if row["status"] == "ok"]
    if not rows:
        raise SystemExit(f"No usable rows (status=ok) in {path}")
    return rows


def build_series(
    rows: list[dict[str, str]], exp: str, metric: str
) -> list[tuple[str, list[tuple[float, float]]]]:
    """Return a list of (model name, [(x, y), ...]) series in MODEL_ORDER."""
    series = []
    for stem in MODEL_ORDER:
        points = sorted(
            (float(row["param"]), float(row[metric]))
            for row in rows
            if row["experiment"] == exp and row["model"] == stem
        )
        if points:
            series.append((display_name(stem), points))
    return series


def fmt(value: float) -> str:
    return f"{value:.8g}"


def plot_commands(
    series: list[tuple[str, list[tuple[float, float]]]],
    show_legend: bool,
) -> str:
    lines = []
    for i, (name, points) in enumerate(series):
        coords = " ".join(f"({fmt(x)},{fmt(y)})" for x, y in points)
        lines.append(
            f"\\addplot+[color=cf{i}, mark={MARKS[i]}, mark size=1.5pt, "
            f"line width=0.9pt, mark options={{solid}}] coordinates {{ {coords} }};"
        )
        if show_legend:
            lines.append(f"\\addlegendentry{{{name}}}")
    return "\n".join(lines)


def axis_options(
    *,
    title: str,
    xlabel: str,
    ylabel: str,
    log_y: bool,
    xticks: str,
    width: str,
    height: str,
    show_legend: bool,
) -> str:
    opts = [
        f"width={width}",
        f"height={height}",
        f"title={{{title}}}",
        f"xlabel={{{xlabel}}}",
        f"ylabel={{{ylabel}}}",
        f"xtick={{{xticks}}}",
        "grid=major",
        "tick label style={font=\\small}",
        "label style={font=\\small}",
        "title style={font=\\small}",
        "scaled y ticks=false",
    ]
    if log_y:
        opts += ["ymode=log", "log basis y=10", "log origin=infty"]
    else:
        opts += ["yticklabel style={/pgf/number format/fixed}"]
    if show_legend:
        opts += [
            "legend pos=north west",
            "legend style={font=\\scriptsize, draw=none, fill=white, "
            "fill opacity=0.85, text opacity=1}",
            "legend cell align=left",
        ]
    return ",\n".join(opts)


def color_definitions() -> str:
    return "\n".join(
        f"\\definecolor{{cf{i}}}{{RGB}}{{{color}}}" for i, color in enumerate(COLORS)
    )


def render_axis(
    series: list[tuple[str, list[tuple[float, float]]]],
    xlabel: str,
    ylabel: str,
    log_y: bool,
    xticks: str,
    width: str = "0.45\\textwidth",
    height: str = "0.32\\textwidth",
    show_legend: bool = True,
    tikz: bool = False,
) -> str:
    """Return PREAMBLE + color definitions + axis.

    With tikz=True the axis is wrapped in a tikzpicture (for a complete
    figure); otherwise the output is meant to be \\input inside one.
    """
    options = axis_options(
        title="",
        xlabel=xlabel,
        ylabel=ylabel,
        log_y=log_y,
        xticks=xticks,
        width=width,
        height=height,
        show_legend=show_legend,
    )
    body = "\n".join(
        [
            "\\begin{axis}[",
            options,
            "]",
            plot_commands(series, show_legend=show_legend),
            "\\end{axis}",
        ]
    )
    if tikz:
        body = "\n".join(["\\begin{tikzpicture}", body, "\\end{tikzpicture}"])
    return f"{PREAMBLE}\n{color_definitions()}\n\n{body}\n"


def wrap_figure(body: str, caption: str, label: str) -> str:
    return "\n".join(
        [
            "\\begin{figure}[tb]",
            "\\centering",
            body,
            f"\\caption{{{caption}}}",
            f"\\label{{{label}}}",
            "\\end{figure}",
            "",
        ]
    )


def render_time_group(
    experiments: list[str],
    per_exp: dict[str, list[tuple[str, list[tuple[float, float]]]]],
    xticks: dict[str, str],
    xlabels: dict[str, str],
    settings: dict[str, str],
) -> str:
    cells = []
    for col, exp in enumerate(experiments):
        _metric, ylabel, log_y, _tag = EXPERIMENTS[exp][1][0]
        options = axis_options(
            title=f"({chr(97 + col)}) {settings[exp]}",
            xlabel=xlabels[exp],
            ylabel=ylabel if col == 0 else "",
            log_y=log_y,
            xticks=xticks[exp],
            width="0.34\\textwidth",
            height="0.28\\textwidth",
            show_legend=col == 0,
        )
        cells.append(
            "\n".join(
                [
                    "\\nextgroupplot[" + options + "]",
                    plot_commands(per_exp[exp], show_legend=col == 0),
                ]
            )
        )
    groupplot = "\n\n".join(cells)
    return "\n".join(
        [
            "\\begin{tikzpicture}",
            "\\begin{groupplot}[",
            "    group style={",
            "        group size=3 by 1,",
            "        horizontal sep=1.5cm,",
            "        xlabels at=edge bottom,",
            "        ylabels at=edge left,",
            "    },",
            "]",
            groupplot,
            "\\end{groupplot}",
            "\\end{tikzpicture}",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results", type=Path, default=Path("tests/eval/param_results/results.csv")
    )
    parser.add_argument("--out", type=Path, default=Path("tests/eval/figures"))
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    standalone_dir = args.out / "standalone"
    standalone_dir.mkdir(parents=True, exist_ok=True)

    rows = load_results(args.results)

    experiments = [
        exp for exp in ("t", "m", "c") if any(r["experiment"] == exp for r in rows)
    ]
    xlabels = {exp: EXPERIMENTS[exp][0] for exp in experiments}
    xticks = {
        exp: ",".join(
            str(int(v))
            for v in sorted(
                {float(row["param"]) for row in rows if row["experiment"] == exp}
            )
        )
        for exp in experiments
    }
    settings = {"t": "$m=5$, $c=50$", "m": "$t=2$, $c=50$", "c": "$t=2$, $m=5$"}

    # Time series per experiment (log y) and size series for the m experiment
    time_series = {
        exp: build_series(rows, exp, "avg_time_seconds") for exp in experiments
    }
    size_series = build_series(rows, "m", "avg_sample_size")

    # Standalone single-axis files
    for exp in experiments:
        _metric, ylabel, log_y, _tag = EXPERIMENTS[exp][1][0]
        text = render_axis(time_series[exp], xlabels[exp], ylabel, log_y, xticks[exp])
        path = standalone_dir / f"axis_rq3_time_{exp}.tex"
        path.write_text(text)
        print(f"Wrote {path}")
    if size_series:
        _metric, ylabel, log_y, _tag = EXPERIMENTS["m"][1][1]
        text = render_axis(size_series, xlabels["m"], ylabel, log_y, xticks["m"])
        path = standalone_dir / "axis_rq3_size_m.tex"
        path.write_text(text)
        print(f"Wrote {path}")

    # Combined time figure: one axis per experiment
    if experiments:
        body = render_time_group(experiments, time_series, xticks, xlabels, settings)
        body = f"{PREAMBLE}\n{color_definitions()}\n{body}"
        caption = (
            "Influence of the parameters on the sampling time of the instance-set "
            "$t$-wise sampling algorithm (logarithmic scale). Lines show the "
            "evaluation models; averages over $r=10$ repetitions ($r=5$ for "
            "Model B). Settings: (a) $m=5$, $c=50$; (b) $t=2$, $c=50$; "
            "(c) $t=2$, $m=5$."
        )
        path = args.out / "rq3_time.tex"
        path.write_text(wrap_figure(body, caption, "fig:rq3-time"))
        print(f"Wrote {path}")

    # Sample size figure for the m experiment
    if size_series:
        _metric, ylabel, _log_y, _tag = EXPERIMENTS["m"][1][1]
        body = render_axis(
            size_series,
            xlabels["m"],
            ylabel,
            log_y=False,
            xticks=xticks["m"],
            width="0.6\\textwidth",
            height="0.4\\textwidth",
            tikz=True,
        )
        caption = (
            "Influence of the number of resampling rounds $m$ on the sample size "
            "of the instance-set $t$-wise sampling algorithm. Lines show the "
            "evaluation models; averages over $r=10$ repetitions ($r=5$ for "
            "Model B) with $t=2$ and $c=50$."
        )
        path = args.out / "rq3_size.tex"
        path.write_text(wrap_figure(body, caption, "fig:rq3-size"))
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
